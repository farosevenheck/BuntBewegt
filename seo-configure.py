#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""BuntBewegt static SEO one-time configuration.
Run before upload: python3 seo-configure.py --domain https://YOUR-ACTUAL-SITE-DOMAIN
No extra packages required. Safe to run more than once if the website domain changes.
"""
from pathlib import Path
from urllib.parse import urlsplit
from xml.sax.saxutils import escape as xml_escape
import argparse
import re
import html
import json

p=argparse.ArgumentParser(description='Create canonical links, JSON-LD and sitemap.xml for your actual domain.')
p.add_argument('--domain',required=True,help='Real public site URL, e.g. https://www.example.org')
a=p.parse_args()
val=a.domain.strip().rstrip('/')
u=urlsplit(val)
if u.scheme!='https' or not u.netloc or u.path not in ('','/') or u.query or u.fragment:
    p.error('Please supply only the HTTPS domain, like https://www.example.org')
if u.netloc.lower() in {'example.com','www.example.com','example.org','www.example.org','your-domain.com','buntbewegt.de'}:
    p.error('This appears to be a sample or a domain belonging to an unrelated site; verify and use the real hosted domain.')
root=Path(__file__).resolve().parent
site=val+'/'
icons=val+'/images/'
all_pages=sorted(root.glob('*.html'))
page_urls=[]

for f in all_pages:
    current=site if f.name=='index.html' else site+f.name
    page_urls.append(current)
    data=f.read_text(encoding='utf-8')
    head=re.search(r'(?is)<head\b[^>]*>(.*?)</head\s*>',data)
    if not head:
        raise RuntimeError('Missing <head>: '+f.name)
    inner=head.group(1)
    inner=re.sub(r'<link rel="canonical" data-seo-canonical="fallback"[^>]*>\s*','',inner,flags=re.I)
    inner=re.sub(r'\s*<!-- SEO-DOMAIN-START -->.*?<!-- SEO-DOMAIN-END -->','',inner,flags=re.S|re.I)
    # Change only metadata generated by the base SEO package, never visible content.
    social_image=icons+'buntbewegt-social-preview.jpg'
    for prop in ('og:image','twitter:image'):
        inner,number=re.subn(r'(<meta\s+[^>]*(?:property|name)="'+prop+r'"\s+content=")[^"]*("[^>]*>)',lambda m:m.group(1)+social_image+m.group(2),inner,count=1,flags=re.I)
        if number!=1: raise RuntimeError('Missing social meta: '+prop+' in '+f.name)
    tm=re.search(r'(?is)<title>(.*?)</title>',inner)
    dm=re.search(r'<meta\s+name="description"\s+content="([^"]*)"\s*/?>',inner,flags=re.I)
    if not tm or not dm: raise RuntimeError('Missing title or description: '+f.name)
    title=html.unescape(re.sub(r'<[^>]*>','',tm.group(1))).strip()
    description=html.unescape(dm.group(1))
    website_id=site+'#website'
    org_id=site+'#organization'
    page_id=current+'#webpage'
    graph=[]
    if f.name=='index.html':
        graph.append({'@type':'Organization','@id':org_id,'name':'BuntBewegt','url':site,
                      'description':'Bewegung, Kreativität und Gemeinschaft in Kiel.',
                      'logo':{'@type':'ImageObject','url':icons+'logo-buntbewegt-neu.png'},
                      'image':icons+'favicon-512.png',
                      'sameAs':['https://www.instagram.com/buntbewegt.de/'],
                      'areaServed':{'@type':'Place','name':'Kiel, Schleswig-Holstein, Deutschland'}})
        graph.append({'@type':'WebSite','@id':website_id,'name':'BuntBewegt','url':site,
                      'inLanguage':'de-DE','publisher':{'@id':org_id}})
    page_type='WebPage'
    if f.name=='kontakt.html': page_type='ContactPage'
    elif f.name=='ueber-buntbewegt.html': page_type='AboutPage'
    elif f.name in ('news-events.html','angebote.html','netzwerk.html','bilder-material.html'): page_type='CollectionPage'
    page={'@type':page_type,'@id':page_id,'url':current,'name':title,'description':description,
          'inLanguage':'de-DE','isPartOf':{'@id':website_id},'about':{'@id':org_id}}
    if f.name!='index.html':
        breadcrumb_id=current+'#breadcrumb'
        page['breadcrumb']={'@id':breadcrumb_id}
        graph.append({'@type':'BreadcrumbList','@id':breadcrumb_id,'itemListElement':[
            {'@type':'ListItem','position':1,'name':'Startseite','item':site},
            {'@type':'ListItem','position':2,'name':title.split(' | BuntBewegt')[0].split(' – BuntBewegt')[0],'item':current}
        ]})
    graph.append(page)
    schema=json.dumps({'@context':'https://schema.org','@graph':graph},ensure_ascii=False,separators=(',',':')).replace('</','<\\/')
    block='''\n<!-- SEO-DOMAIN-START -->
<link rel="canonical" href="%s">
<meta property="og:url" content="%s">
<script type="application/ld+json">%s</script>
<!-- SEO-DOMAIN-END -->
''' % (html.escape(current,quote=True),html.escape(current,quote=True),schema)
    inner+=block
    data=data[:head.start(1)]+inner+data[head.end(1):]
    f.write_text(data,encoding='utf-8')

(root/'robots.txt').write_text('User-agent: *\nAllow: /\n\nSitemap: '+site+'sitemap.xml\n',encoding='utf-8')
xml=['<?xml version="1.0" encoding="UTF-8"?>','<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
for url in [site]+[u for u in page_urls if u!=site]:
    xml.append('  <url><loc>'+xml_escape(url)+'</loc></url>')
xml.append('</urlset>')
(root/'sitemap.xml').write_text('\n'.join(xml)+'\n',encoding='utf-8')
print('SEO configured for',site)
print('Canonical + structured data:',len(all_pages),'pages; sitemap:',len(page_urls),'URLs')
